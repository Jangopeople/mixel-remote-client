const language = (navigator.language || 'en').slice(0, 2).toLowerCase();
export function t(text) { return (TEXTS[language] && TEXTS[language][text]) || text; }
export function applyTexts() {
  document.documentElement.lang = TEXTS[language] ? language : 'en';
  for (const node of document.querySelectorAll('[data-t]')) node.textContent = t(node.textContent.trim());
  for (const node of document.querySelectorAll('[data-t-placeholder]')) node.placeholder = t(node.placeholder);
}
