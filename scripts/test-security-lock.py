#!/usr/bin/env python3
"""Tests for patch-security-lock.py: apply, restore, idempotence, refusal, line endings."""
import importlib.util
import json
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

HERE = Path(__file__).resolve().parent
SCRIPT = HERE / "patch-security-lock.py"
spec = importlib.util.spec_from_file_location("security_lock", SCRIPT)
L = importlib.util.module_from_spec(spec); spec.loader.exec_module(L)

HEAD = "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 3\n\n"
def pkg(name, version, deps=(), source='registry+https://github.com/rust-lang/crates.io-index', checksum='00'):
    text = f'[[package]]\nname = "{name}"\nversion = "{version}"\n'
    if source: text += f'source = "{source}"\n'
    if checksum and source and source.startswith('registry'): text += f'checksum = "{checksum}"\n'
    if deps: text += 'dependencies = [\n' + ''.join(f' "{d}",\n' for d in deps) + ']\n'
    return text
OLD = HEAD + "\n".join([pkg("app", "1.0.0", ["bytes", "ipc", "old-only"], source=None), pkg("bytes", "1.10.1", checksum="aa"),
                         pkg("ipc", "0.7.3", ["bytes"], source=None), pkg("old-only", "0.1.0", checksum="bb")])
NEW = HEAD + "\n".join([pkg("app", "1.0.0", ["bytes", "fresh", "ipc"], source=None), pkg("bytes", "1.11.1", checksum="cc"),
                         pkg("fresh", "0.6.5", checksum="dd"), pkg("ipc", "0.7.3", ["bytes", "fresh"], source=None)])
# The same tree on another platform: ipc comes from git instead of a vendored path.
OTHER = OLD.replace('name = "ipc"\nversion = "0.7.3"\n', 'name = "ipc"\nversion = "0.7.3"\nsource = "git+https://example.invalid/ipc#abc"\n')

class SecurityLock(unittest.TestCase):
    def setUp(self):
        self.tmp = Path(tempfile.mkdtemp()); self.addCleanup(lambda: subprocess.run(['rm', '-rf', str(self.tmp)]))
        self.spec = {"apply": L.direction(OLD, NEW), "restore": L.direction(NEW, OLD)}
        self.specfile = self.tmp / "spec.json"; self.specfile.write_text(json.dumps(self.spec))
        L.SPEC = self.specfile

    def run_main(self, *args):
        old = sys.argv; sys.argv = ["x", *args]
        try: return L.main()
        finally: sys.argv = old

    def lock(self, text, crlf=False):
        root = self.tmp / "root"; root.mkdir(exist_ok=True)
        (root / "Cargo.lock").write_bytes((text.replace("\n", "\r\n") if crlf else text).encode()); return root

    def test_apply_and_restore_are_exact_inverses(self):
        self.assertEqual(L.apply(OLD, self.spec["apply"]), NEW)
        self.assertEqual(L.apply(NEW, self.spec["restore"]), OLD)

    def test_other_platform_keeps_its_own_source_line(self):
        result = L.apply(OTHER, self.spec["apply"])
        self.assertIn('source = "git+https://example.invalid/ipc#abc"', result)
        self.assertEqual(result.replace('source = "git+https://example.invalid/ipc#abc"\n', ''), NEW)
        self.assertEqual(L.apply(result, self.spec["restore"]), OTHER)

    def test_cli_idempotent_and_keeps_crlf(self):
        root = self.lock(OLD, crlf=True)
        self.assertEqual(self.run_main("--check", str(root)), 0)
        self.assertEqual((root / "Cargo.lock").read_bytes(), OLD.replace("\n", "\r\n").encode())
        self.assertEqual(self.run_main(str(root)), 0)
        self.assertEqual((root / "Cargo.lock").read_bytes(), NEW.replace("\n", "\r\n").encode())
        self.assertEqual(self.run_main(str(root)), 0)  # already applied
        self.assertEqual(self.run_main("--restore", str(root)), 0)
        self.assertEqual((root / "Cargo.lock").read_bytes(), OLD.replace("\n", "\r\n").encode())

    def test_partial_or_foreign_lock_is_refused_without_writing(self):
        partial = OLD.replace('version = "1.10.1"\nsource = "registry+https://github.com/rust-lang/crates.io-index"\nchecksum = "aa"',
                              'version = "1.11.1"\nsource = "registry+https://github.com/rust-lang/crates.io-index"\nchecksum = "cc"')
        root = self.lock(partial)
        self.assertEqual(self.run_main(str(root)), 1)
        self.assertEqual((root / "Cargo.lock").read_text(), partial)

    def test_shipped_spec_is_well_formed(self):
        shipped = json.loads((HERE / "security" / "cargo-lock-20261112.json").read_text())
        for side in ("apply", "restore"):
            self.assertEqual(set(shipped[side]), {"changed", "removed", "added"})
        removed, added = set(shipped["apply"]["removed"]), set(shipped["apply"]["added"])
        for name, before, after in (("rustls", "0.23.28", "0.23.46"), ("rustls-webpki", "0.103.3", "0.103.16"), ("tokio", "1.44.2", "1.51.6"),
                                    ("bytes", "1.10.1", "1.11.1"), ("crossbeam-channel", "0.5.13", "0.5.15"), ("openssl", "0.10.68", "0.10.78")):
            self.assertIn(f"{name} {before}", removed); self.assertIn(f"{name} {after}", added)
        self.assertEqual(set(shipped["restore"]["removed"]), added); self.assertEqual(set(shipped["restore"]["added"]), removed)

if __name__ == "__main__":
    unittest.main()
