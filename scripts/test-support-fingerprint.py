def block(source, anchor):
    start = source.index(anchor)
    begin = source.index('{', start)
    depth = 0
    for end in range(begin, len(source)):
        depth += (source[end] == '{') - (source[end] == '}')
        if depth == 0:
            return source[start:end + 1]
    raise RuntimeError('Unclosed source block')


def fixture(source):
    # Only the hardware/configuration boundary is replaced. SHA512 and all AES-like
    # primitives, parameter selection, cache and public getters are literal source.
    constructor = block(source, '    fn new() -> Self {\n        let mut sys')
    fields = dict(eol='\n', endianness='LE', brand='FixtureCPU', speed_max='2400',
                  cores='8', physical_cores='4', mem_total='16777216', platform='linux',
                  arch='x86_64', id='1234567890123456', addr='abcdef0123456789')
    values = ',\n'.join(f'            {key}: {json.dumps(value)}.to_string()' for key, value in fields.items())
    replacement = '    fn new() -> Self {\n        INFO_CALLS.fetch_add(1, std::sync::atomic::Ordering::SeqCst);\n        FingerprintingInfo {\n' + values + '\n        }\n    }'
    source = source.replace(constructor, replacement, 1).replace('use sysinfo::System;\n', '', 1)
    return source + '\nstatic INFO_CALLS: std::sync::atomic::AtomicUsize = std::sync::atomic::AtomicUsize::new(0);\n'


