def run(command, out, name, env=None, expected=0):
    result = subprocess.run(command, env=env, stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                            encoding='utf-8', errors='strict', timeout=90)
    (out / (name + '.log')).write_text(result.stdout, encoding='utf-8')
    if result.returncode != expected:
        raise RuntimeError(f'{name} returned {result.returncode}, expected {expected}: {result.stdout[-2000:]}')
    return result.stdout


def materialization(original, out):
    corrected = P.transform(original)
    assert P.inverse(corrected) == original
    assert b'static mut ' not in corrected
    assert b'allow(static_mut_refs)' not in corrected
    refusals = 0
    for newline in [b'\n', b'\r\n']:
        root = out / ('materialization-lf' if newline == b'\n' else 'materialization-crlf')
        target = root / P.TARGET
        target.parent.mkdir(parents=True)
        raw = original.replace(b'\n', newline)
        target.write_bytes(raw)
        # Reject both a symlinked owned file and a hard-linked file before writes.
        retained = target.with_name('retained-original.rs')
        target.rename(retained)
        for kind in ['symlink', 'hardlink']:
            if kind == 'symlink':
                target.symlink_to(retained)
            else:
                os.link(retained, target)
            try:
                P.apply(root)
            except RuntimeError:
                assert retained.read_bytes() == raw
                refusals += 1
            else:
                raise AssertionError('Nonowned source alias accepted')
            target.unlink()
        retained.rename(target)
        P.apply(root, check=True)
        assert target.read_bytes() == raw
        P.apply(root)
        applied = target.read_bytes()
        assert applied == corrected.replace(b'\n', newline)
        P.apply(root)
        assert target.read_bytes() == applied
        P.apply(root, restore=True)
        assert target.read_bytes() == raw
        for value in [raw + b'// drift\n', applied + b'// drift\n', raw[:-1],
                      raw.replace(b'\n', b'\r\n', 1) if newline == b'\n' else raw.replace(b'\r\n', b'\n', 1)]:
            target.write_bytes(value)
            for restore in [False, True]:
                try:
                    P.apply(root, restore=restore)
                except RuntimeError:
                    assert target.read_bytes() == value
                    refusals += 1
                else:
                    raise AssertionError('Source drift accepted')
        target.write_bytes(raw)
    print(f'PASS LF/CRLF check/apply/idempotence/restore; {refusals} drift refusals before writes')
    return corrected


def reparse_controls(original, out):
    # Model the public Windows reparse attribute through the actual lstat/apply
    # path. No junction or native Windows operation is executed on this host.
    root = out / "reparse-attribute-model"
    target = root / P.TARGET
    target.parent.mkdir(parents=True)
    target.write_bytes(original)
    original_lstat = Path.lstat
    refusals = 0
    for selected in (root, root / "libs", target):
        def modeled_lstat(path, *args, **kwargs):
            actual = original_lstat(path, *args, **kwargs)
            return (SimpleNamespace(st_mode=actual.st_mode, st_nlink=actual.st_nlink,
                                    st_file_attributes=0x400) if path == selected else actual)
        for mode in ({"check": True}, {}, {"restore": True}):
            before = target.read_bytes()
            with patch.object(Path, "lstat", modeled_lstat):
                try:
                    P.apply(root, **mode)
                except RuntimeError as error:
                    assert str(error).startswith("Unsafe fingerprint source")
                else:
                    raise AssertionError("Reparse attribute source alias accepted")
            assert target.read_bytes() == before
            refusals += 1
    print(f"PASS {refusals} root/parent/file reparse attribute refusals before writes; explicit Windows attribute model")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, required=True)
    parser.add_argument('--evidence-dir', type=Path)
    dependency_mode = parser.add_mutually_exclusive_group()
    dependency_mode.add_argument('--offline', action='store_true', help='Require the exact fixture dependencies already cached; perform no fetch')
    dependency_mode.add_argument('--fresh-cargo-home', action='store_true', help='Qualify an empty owned cache: retain its original offline refusal, then locked fetch and offline build')
    args = parser.parse_args()
    out = (args.evidence_dir or Path(tempfile.mkdtemp(prefix='mixel-fingerprint-controls-'))).resolve()
    out.mkdir(parents=True, exist_ok=True)
    original, _ = P.normalize((args.source / P.TARGET).read_bytes())
    if P.digest(original) != P.BEFORE_SHA:
        original = P.inverse(original)
    corrected = materialization(original, out)
    reparse_controls(original, out)
    (out / 'original-fingerprint.rs').write_bytes(original)
    (out / 'corrected-fingerprint.rs').write_bytes(corrected)
    crate = out / 'algorithm-crate'
    (crate / 'src').mkdir(parents=True)
    (crate / 'Cargo.toml').write_text('''[package]
name = "mixel-fingerprint-source-controls"
version = "0.0.0"
edition = "2021"
[dependencies]
sha2 = "=0.10.8"
serde = "=1.0.228"
serde_derive = "=1.0.228"
''')
    # Public visibility is fixture-only for assertions over original private cache
    # and deterministic constructor; no candidate production visibility changes.
    def exposed(source):
        source = fixture(source)
        for needle in ['static mut CACHED_FINGERPRINTS:', 'static CACHED_FINGERPRINTS:',
                       'static INFO_CALLS:', 'fn calculate_fingerprint(']:
            source = source.replace(needle, 'pub ' + needle)
        source = source.replace('    id: String,', '    pub id: String,')
        return source
    main_source = '#![allow(dead_code, unused_variables)]\nmod original {\n' + exposed(original.decode()) + '\n}\nmod corrected {\n' + exposed(corrected.decode()) + '\n}\n' + RUST_CONTROLS
    (crate / 'src/main.rs').write_text(main_source)
    # Keep rustup's rustc proxy executable name; resolving its symlink to
    # rustup changes the selected tool's multicalled command.
    rustc = Path(os.environ.get('RUSTC_BIN', shutil.which('rustc') or '')).absolute()
    cargo = rustc.parent / 'cargo'
    env = dict(os.environ, RUSTC=str(rustc), RUSTFLAGS='-D warnings -A unknown-lints')
    lock = crate / 'Cargo.lock'
    lock.write_text(FIXTURE_LOCK, encoding='utf-8')
    if args.fresh_cargo_home:
        cargo_home = out / 'fresh-cargo-home'
        cargo_home.mkdir()
        env['CARGO_HOME'] = str(cargo_home)
    run([str(rustc), '--version'], out, 'rust-version')
    if args.fresh_cargo_home:
        original_cold = run([str(cargo), 'build', '--offline', '--locked', '--manifest-path', str(crate / 'Cargo.toml')], out, 'original-empty-cache-offline-refusal', env, expected=101)
        assert 'no matching package named' in original_cold
    if not args.offline:
        run([str(cargo), 'fetch', '--locked', '--manifest-path', str(crate / 'Cargo.toml')], out, 'exact-locked-dependency-fetch', env)
    run([str(cargo), 'build', '--offline', '--locked', '--manifest-path', str(crate / 'Cargo.toml')], out, 'actual-source-build', env)
    assert lock.read_bytes() == FIXTURE_LOCK.encode('utf-8')
    binary = crate / 'target/debug/mixel-fingerprint-source-controls'
    negative = run([str(binary), 'original-first-cache'], out, 'original-first-cache-negative', expected=101)
    assert 'first returned fingerprint must be cached' in negative
    collision = run([str(binary), 'original-key-collision'], out, 'original-key-collision-negative', expected=101)
    assert 'distinct parameter vectors must not share cached digests' in collision
    for mode in ['first-cache', 'equivalence', 'key-collisions', 'concurrent', 'info-first']:
        print(run([str(binary), mode], out, mode).strip())
    # Demonstrate that the equivalence/first-call controls detect plausible
    # behavioral regressions; each compiled variant is run only in its own process.
    variants = [
        ('cache-key-loss', 'let cache_key = parameters.clone();', 'let cache_key = vec![parameters.join("")];', 'key-collisions'),
        ('parameter-order', '.iter()\n        .filter_map', '.iter().rev()\n        .filter_map', 'equivalence'),
        ('primitive-key', '    base\n}', '    key\n}', 'equivalence'),
    ]
    candidate_fixture = exposed(corrected.decode())
    original_fixture = exposed(original.decode())
    for name, old, new, mode in variants:
        if candidate_fixture.count(old) != 1:
            raise AssertionError('Bad-variant source anchor changed')
        modified = candidate_fixture.replace(old, new, 1)
        (crate / 'src/main.rs').write_text('#![allow(dead_code, unused_variables)]\nmod original {\n' + original_fixture + '\n}\nmod corrected {\n' + modified + '\n}\n' + RUST_CONTROLS)
        # Coarse file timestamps can otherwise let Cargo reuse the preceding variant.
        run([str(cargo), 'clean', '--manifest-path', str(crate / 'Cargo.toml'),
             '-p', 'mixel-fingerprint-source-controls'], out, name + '-clean', env)
        run([str(cargo), 'build', '--offline', '--locked', '--manifest-path', str(crate / 'Cargo.toml')], out, name + '-build', env)
        run([str(binary), mode], out, name + '-negative', expected=101)
    (crate / 'src/main.rs').write_text(main_source)
    assert lock.read_bytes() == FIXTURE_LOCK.encode('utf-8')
    print('PASS three compiled digest/order/cache-key corruptions refuse101')
    print('PASS original first-call and warm-key-collision failures101; actual SHA2 primitives preserved; original concurrency not executed')


if __name__ == '__main__':
    main()
